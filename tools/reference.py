"""Write the reference pages of the documentation from the code.

    python tools/reference.py            write docs/reference/commands.md
    python tools/reference.py --check    exit 1 if it is out of date

**Commands** (``docs/reference/commands.md``): the ``--help`` of every command, as the
parsers print it at 88 columns.

"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
OUT = DOCS / "reference"
COLUMNS = 88


# ---- commands ---------------------------------------------------------------------------

def command_groups():
    """``(name, description, [(action, help text), ...])`` for every command group."""
    os.environ["COLUMNS"] = str(COLUMNS)          # argparse wraps to this width
    from flowreel.cli.camera import CameraCommand
    from flowreel.cli.compose import ComposeCommand
    from flowreel.cli.film import FilmCommand
    from flowreel.cli.jobs import JobsCommand
    from flowreel.cli.project import ProjectCommand
    from flowreel.cli.shot import ShotCommand
    groups = []
    for cls in (ProjectCommand, ShotCommand, CameraCommand, ComposeCommand, FilmCommand,
                JobsCommand):
        parser = argparse.ArgumentParser(prog="flowreel")
        group = cls().setup_parser(parser.add_subparsers())
        actions = [a for a in group._actions if isinstance(a, argparse._SubParsersAction)]
        helps = [(name, sub.format_help().rstrip())
                 for a in actions for name, sub in a.choices.items()]
        groups.append((cls.name, cls.description, helps))
    return groups


def commands_page() -> str:
    lines = ["# Commands", "",
             "Every command and its options, as `flowreel <command> <action> --help` prints "
             "them.", "This page is generated by `tools/reference.py` from the commands' "
             "own help, so it", "is always the installed version's. How the commands are "
             "used together, with", "examples and output, is in the guide's "
             "[commands](../commands.md) page.", ""]
    for name, description, helps in command_groups():
        lines += [f"## `{name}`", "", description + ".", ""]
        for action, text in helps:
            lines += [f"### `flowreel {name} {action}`", "", "```text", text, "```", ""]
    return "\n".join(lines).rstrip() + "\n"


# ---- writing and checking ------------------------------------------------------------------

def pages() -> tuple[dict[Path, str], list[str]]:
    """Every generated page by path, and what is missing from the guide (nothing yet)."""
    return {OUT / "commands.md": commands_page()}, []


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="write nothing; exit 1 if a page is out of date or a key "
                             "is not documented")
    args = parser.parse_args(argv)
    written, missing = pages()
    stale = [p for p, text in written.items()
             if not p.is_file() or p.read_text() != text]
    for line in missing:
        print(f"not documented: {line}", file=sys.stderr)
    if args.check:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)} (run python tools/reference.py)",
                  file=sys.stderr)
        return 1 if stale or missing else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for p in stale:
        p.write_text(written[p])
        print(f"wrote {p.relative_to(ROOT)}")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
